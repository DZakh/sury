// Puts the rendered charts on the `benchmarks` branch, which the pages under
// docs/benchmarks/ embed the timings from.
//
// The timings are the one measurement a pull request cannot gate, because they
// move with the runner. They used to be committed back to main on every push,
// which a protected branch declines: a bot cannot open the pull request its own
// rule asks for. So they go to a branch nothing is developed on, and the pages
// reach them by URL, which is what lets the markdown on main stay the same from
// one measurement to the next.
//
// The commit is built with plumbing against a temporary index rather than with
// a worktree on a branch of its own. Nothing here touches the checkout, the
// index or the branch namespace of the clone it runs in, so a contributor
// seeding the branch by hand does not have it stand on their work.
//
// The branch is replaced by a single commit each run rather than appended to:
// every run republishes every file, and a year of them is a year of blobs
// nobody reads. Replacing it is also why this takes the charts the caller just
// rendered rather than reading a directory - a set missing a topic would
// publish as the whole branch and break the page whose file it left out.
import { execFileSync } from "node:child_process";
import { mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";

const BRANCH = "benchmarks";

const README = `# Benchmark charts

Generated by \`pnpm benchmarks --publish\` on every push to \`main\`, and embedded
by the pages under \`docs/benchmarks/\` on the default branch. Nothing is
developed here, and this branch is rewritten on every run.
`;

type Options = { cwd?: string; env?: NodeJS.ProcessEnv; quiet?: boolean };

const git = (args: string[], { cwd, env, quiet = true }: Options = {}): string =>
  execFileSync("git", args, {
    cwd,
    encoding: "utf8",
    env: env === undefined ? process.env : { ...process.env, ...env },
    stdio: quiet ? ["ignore", "pipe", "pipe"] : "inherit",
  })?.trim() ?? "";

// A runner has no identity configured and a contributor's clone does, so this
// supplies one rather than replacing one.
const identify = (key: string, value: string): void => {
  try {
    git(["config", key]);
  } catch {
    git(["config", key, value]);
  }
};

export const publish = (charts: Map<string, string>): void => {
  identify("user.name", "github-actions[bot]");
  identify("user.email", "41898282+github-actions[bot]@users.noreply.github.com");

  const staging = mkdtempSync(path.join(tmpdir(), "benchmark-charts-"));
  const index = path.join(staging, "..", `benchmark-index-${process.pid}`);
  try {
    for (const [name, contents] of charts) writeFileSync(path.join(staging, name), contents);
    writeFileSync(path.join(staging, "README.md"), README);

    const env = {
      GIT_DIR: git(["rev-parse", "--absolute-git-dir"]),
      GIT_WORK_TREE: staging,
      GIT_INDEX_FILE: index,
    };
    git(["add", "-A"], { cwd: staging, env });
    const tree = git(["write-tree"], { cwd: staging, env });
    const commit = git(["commit-tree", tree, "-m", "chore: republish the benchmark charts"], { cwd: staging, env });
    git(["push", "--force", "origin", `${commit}:refs/heads/${BRANCH}`], { cwd: staging, env, quiet: false });
  } finally {
    rmSync(staging, { recursive: true, force: true });
    rmSync(index, { force: true });
  }
};
