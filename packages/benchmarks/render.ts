// One topic's measurements as the markdown page under docs/benchmarks/.
//
// Rendering is separate from measuring so `cli.ts` can re-render a committed
// golden without re-running anything: on a pull request the timings are not
// remeasured, and the page still has to come out byte-identical.
import { type Row, type Table, type Topic, formatCell, winners } from "./table";

// How the machine that timed a run is named on the page it produced.
export const provenance = (): string =>
  `node ${process.version.slice(1)} · ${process.platform} ${process.arch}`;

const cell = (row: Row, index: number, won: boolean): string => {
  const text = formatCell(row.cells[index]!, row.format);
  return won ? `**${text}**` : text;
};

const renderTable = (table: Table): string => {
  const head = ["", ...table.columns];
  const rule = table.align === "center" ? ":---:" : "---:";
  const lines = [
    `| ${head.join(" | ")} |`,
    `| ${head.map((_, i) => (i === 0 ? "---" : rule)).join(" | ")} |`,
  ];
  for (const row of table.rows) {
    const won = winners(row);
    const label = row.note === undefined ? row.label : `${row.label}<br><sub>${row.note}</sub>`;
    lines.push(`| ${[label, ...row.cells.map((_, i) => cell(row, i, won[i]!))].join(" | ")} |`);
  }
  if (table.note !== undefined) lines.push("", table.note);
  return lines.join("\n");
};

const nav = (topics: { id: string; label: string }[], current: string): string =>
  `**Benchmarks:** ${topics
    .map((t) => (t.id === current ? t.label : `[${t.label}](${t.id}.md)`))
    .join(" | ")}`;

export const renderPage = (
  topic: Topic,
  all: { id: string; label: string }[],
  machine: string,
): string =>
  [
    "<!-- Generated by `pnpm benchmarks --write`. Do not edit by hand. -->",
    "",
    `# ${topic.title}`,
    "",
    nav(all, topic.id),
    "",
    topic.blurb,
    "",
    `Measured against ${topic.versions.join(", ")}.`,
    "",
    "## Bundle size",
    "",
    renderTable(topic.bundleSize),
    "",
    "## Features",
    "",
    renderTable(topic.features),
    "",
    "## Performance",
    "",
    renderTable(topic.performance),
    "",
    `<sub>Timed on ${machine}. Rerun on every push to main, so a row moves with the runner as well as with the code.</sub>`,
    "",
    "## Conformance",
    "",
    renderTable(topic.conformance),
    "",
  ].join("\n");
