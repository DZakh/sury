// One topic's measurements as the markdown page under docs/benchmarks/.
//
// Rendering is separate from measuring so `cli.ts` can re-render a committed
// golden without re-running anything: on a pull request the timings are not
// remeasured, and the page still has to come out byte-identical.
import { type Row, type Table, type Topic, formatCell, winners } from "./table";

// Where main republishes the timing charts. A protected branch is what the
// bot cannot push to, so the numbers that have to be remeasured live on a
// branch of their own and the page reaches them by URL, which lets this
// markdown stay the same from one measurement to the next.
const CHARTS = "https://raw.githubusercontent.com/DZakh/sury/benchmarks";

// GitHub picks the cut by the theme the reader is on, and proxies both through
// its image cache, so a chart can lag the run that produced it by a few
// minutes. The `alt` is what a reader gets where the image does not load, so it
// says which numbers are missing rather than naming the picture.
const chart = (topic: Topic): string =>
  [
    "<picture>",
    `  <source media="(prefers-color-scheme: dark)" srcset="${CHARTS}/${topic.id}-performance-dark.svg">`,
    `  <img alt="${topic.label} timings, one bar per library, remeasured on every push to main" src="${CHARTS}/${topic.id}-performance.svg">`,
    "</picture>",
  ].join("\n");

const cell = (row: Row, index: number, won: boolean): string => {
  const text = formatCell(row.cells[index]!, row.format);
  return won ? `**${text}**` : text;
};

const renderTable = (table: Table): string => {
  const head = ["", ...table.columns];
  const rule = table.align === "center" ? ":---:" : "---:";
  const lines = [
    `| ${head.join(" | ")} |`,
    `| ${head.map((_, i) => (i === 0 ? "---" : rule)).join(" | ")} |`,
  ];
  for (const row of table.rows) {
    const won = winners(row);
    const label = row.note === undefined ? row.label : `${row.label}<br><sub>${row.note}</sub>`;
    lines.push(`| ${[label, ...row.cells.map((_, i) => cell(row, i, won[i]!))].join(" | ")} |`);
  }
  if (table.note !== undefined) lines.push("", table.note);
  return lines.join("\n");
};

const nav = (topics: { id: string; label: string }[], current: string): string =>
  `**Benchmarks:** ${topics
    .map((t) => (t.id === current ? t.label : `[${t.label}](${t.id}.md)`))
    .join(" | ")}`;

export const renderPage = (topic: Topic, all: { id: string; label: string }[]): string =>
  [
    "<!-- Generated by `pnpm benchmarks --write`. Do not edit by hand. -->",
    "",
    `# ${topic.title}`,
    "",
    nav(all, topic.id),
    "",
    topic.blurb,
    "",
    `Measured against ${topic.versions.join(", ")}.`,
    "",
    "## Features",
    "",
    renderTable(topic.features),
    "",
    "## Performance",
    "",
    chart(topic),
    "",
    topic.performanceNote,
    "",
    "<sub>Remeasured on every push to main and republished as the chart above, so a bar moves with the runner as well as with the code.</sub>",
    "",
    "## Bundle size",
    "",
    renderTable(topic.bundleSize),
    "",
    "## Conformance",
    "",
    renderTable(topic.conformance),
    "",
  ].join("\n");
